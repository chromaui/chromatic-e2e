import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { expect, onTestFinished, test } from "vitest";

import { generateStoryIndex } from "./story-index";

/** Stories files and the `index.json` that `storybook build` generated from them */
const FIXTURES = resolve(import.meta.dirname, "../../../archive-storybook/fixtures");

test("matches index.json generated by Storybook", async () => {
  const projectRoot = await createProject();
  const archivesDir = join(projectRoot, "test-results/chromatic-archives");
  await cp(FIXTURES, archivesDir, { recursive: true });

  const index = await generateStoryIndex({ archivesDir, projectRoot });
  const expected = JSON.parse(await readFile(join(FIXTURES, "index.json"), "utf-8"));

  // Compare serialized JSON to catch differences in key order too
  expect(JSON.stringify(index, null, 2)).toBe(JSON.stringify(expected, null, 2));
});

test("ignores files that are not stories files", async () => {
  const projectRoot = await createProject();
  const archivesDir = join(projectRoot, "chromatic-archives");

  await writeStoriesFile(archivesDir, "button.stories.json", {
    title: "button",
    stories: [{ name: "primary" }],
  });
  await writeFile(join(archivesDir, "button-primary.w1280h720.snapshot.json"), "{}");
  await mkdir(join(archivesDir, "archive"));

  const index = await generateStoryIndex({ archivesDir, projectRoot });

  expect(Object.keys(index.entries)).toEqual(["button--primary"]);
});

test("falls back to Storybook's story ID when stories file has no __id", async () => {
  const projectRoot = await createProject();
  const archivesDir = join(projectRoot, "chromatic-archives");

  await writeStoriesFile(archivesDir, "home-page.stories.json", {
    title: "home page",
    stories: [{ name: "renders heading" }, { name: "custom", parameters: { __id: "custom-id" } }],
  });

  const index = await generateStoryIndex({ archivesDir, projectRoot });

  expect(Object.keys(index.entries)).toEqual(["home-page--renders-heading", "custom-id"]);
});

test("combines default, file and story tags", async () => {
  const projectRoot = await createProject();
  const archivesDir = join(projectRoot, "chromatic-archives");

  await writeStoriesFile(archivesDir, "button.stories.json", {
    title: "button",
    tags: ["file-tag", "!manifest"],
    stories: [{ name: "primary", tags: ["story-tag"] }],
  });

  const index = await generateStoryIndex({ archivesDir, projectRoot });

  expect(index.entries["button--primary"].tags).toEqual(["dev", "test", "file-tag", "story-tag"]);
});

test("throws on duplicate story IDs", async () => {
  const projectRoot = await createProject();
  const archivesDir = join(projectRoot, "chromatic-archives");

  for (const filename of ["button-1.stories.json", "button-2.stories.json"]) {
    await writeStoriesFile(archivesDir, filename, {
      title: "button",
      stories: [{ name: "primary" }],
    });
  }

  await expect(generateStoryIndex({ archivesDir, projectRoot })).rejects.toThrow(
    [
      "Duplicate stories with id: button--primary",
      "  - ./chromatic-archives/button-1.stories.json",
      "  - ./chromatic-archives/button-2.stories.json",
    ].join("\n"),
  );
});

async function createProject() {
  const projectRoot = await mkdtemp(join(tmpdir(), "story-index-"));
  onTestFinished(() => rm(projectRoot, { recursive: true, force: true }));

  return projectRoot;
}

async function writeStoriesFile(archivesDir: string, filename: string, content: object) {
  await mkdir(archivesDir, { recursive: true });
  await writeFile(join(archivesDir, filename), JSON.stringify(content));
}
